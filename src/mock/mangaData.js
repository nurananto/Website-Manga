export function getUnlockDate(unlockTimeStr) {
  const now = new Date();
  if (!unlockTimeStr) return now;

  const match = unlockTimeStr.match(/(\d+)/);
  if (!match) return now;

  const value = parseInt(match[1], 10);
  if (unlockTimeStr.includes('minggu')) {
    now.setDate(now.getDate() + value * 7);
  } else if (unlockTimeStr.includes('hari')) {
    now.setDate(now.getDate() + value);
  } else if (unlockTimeStr.includes('jam')) {
    now.setHours(now.getHours() + value);
  } else if (unlockTimeStr.includes('menit')) {
    now.setMinutes(now.getMinutes() + value);
  }
  return now;
}

